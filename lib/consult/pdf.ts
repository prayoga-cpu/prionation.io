// Renders a real Claude-generated diagnostic (lib/consult/prompt.ts's
// DiagnosticResult) into a short, downloadable, on-brand PDF report — the
// actual "quick diagnostic / roadmap" deliverable prospects expect from the
// Guided Intake tab. Embeds the site's real brand fonts (Rubik, Black Han
// Sans) so the report reads as authentically PRIONATION.io, not a generic
// pdfkit default.

import { readFileSync } from "node:fs";
