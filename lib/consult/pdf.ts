// Pre-converted copies of the site's real brand fonts (app/[locale]/layout.tsx
// loads the same families as woff2). pdfkit can't embed woff2 directly, and
// decoding it at runtime (wawoff2, an Emscripten/WASM build) turned out to be
// unreliable once bundled ("Unknown font format" — the WASM binding didn't
// survive Turbopack, even marked external) — so these .ttf files are
// converted once and committed instead of decoded on every request. To
// regenerate after a brand font update, decode the new woff2 with wawoff2
// (`npx --package wawoff2 -e "require('wawoff2').decompress(...)"`) and
// overwrite the files below.
const FONT_FILES = {
  rubik: "lib/consult/fonts/rubik-regular.ttf",
  rubikBold: "lib/consult/fonts/rubik-bold.ttf",
  blackHanSans: "lib/consult/fonts/black-han-sans.ttf",
} as const;

let fonts: Record<keyof typeof FONT_FILES, Buffer> | null = null;

function loadFonts() {
  if (!fonts) {
    fonts = Object.fromEntries(
      Object.entries(FONT_FILES).map(([key, relPath]) => [
        key,
        // turbopackIgnore: these exact files are force-included via
        // next.config.ts's outputFileTracingIncludes — without this,
        // Turbopack's tracer treats process.cwd() + a variable as
        // untraceable and (per its own build warning) falls back to
        // tracing the whole project.
        readFileSync(join(/* turbopackIgnore: true */ process.cwd(), relPath)),
      ]),
    ) as Record<keyof typeof FONT_FILES, Buffer>;
  }
  return fonts;
}

